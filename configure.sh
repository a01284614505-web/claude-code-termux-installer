#!/usr/bin/env bash

# Interactive Claude Code custom API configuration for Termux.
# It is self-contained so it can be executed with:
#   curl -fsSL https://raw.githubusercontent.com/galiandan/claude-code-termux-installer/main/configure.sh | bash

set -Eeuo pipefail

CONFIG_DIR="${HOME}/.config/claude-code"
CONFIG_FILE="${CONFIG_DIR}/credentials.env"

if [[ -t 1 && -z "${NO_COLOR:-}" ]]; then
    RED=$'\033[0;31m'
    GREEN=$'\033[0;32m'
    YELLOW=$'\033[1;33m'
    BLUE=$'\033[0;34m'
    NC=$'\033[0m'
else
    RED=''
    GREEN=''
    YELLOW=''
    BLUE=''
    NC=''
fi

print_header() {
    printf '%s\n' "${BLUE}============================================================${NC}"
    printf '%s\n' "${BLUE}$1${NC}"
    printf '%s\n' "${BLUE}============================================================${NC}"
}

info() {
    printf '%s %s\n' "${YELLOW}[INFO]${NC}" "$1"
}

success() {
    printf '%s %s\n' "${GREEN}[OK]${NC}" "$1"
}

die() {
    printf '%s %s\n' "${RED}[ERROR]${NC}" "$1" >&2
    exit 1
}

usage() {
    cat <<'EOF'
Claude Code custom API configuration for Termux

Usage:
  bash configure.sh
  curl -fsSL https://raw.githubusercontent.com/galiandan/claude-code-termux-installer/main/configure.sh | bash

The script asks for an API base URL and API key, then writes:
  ~/.config/claude-code/credentials.env
EOF
}

require_terminal() {
    [[ -r /dev/tty && -w /dev/tty ]] || die "需要交互式终端。请在 Termux 终端中运行此脚本。"
    exec </dev/tty >/dev/tty
}

check_termux() {
    [[ "${PREFIX:-}" == */com.termux/files/usr || -d /data/data/com.termux/files/usr ]] || \
        die "此脚本仅支持 Android/Termux，请在 Termux 中运行。"
    [[ "$(uname -m)" == "aarch64" ]] || \
        die "此脚本仅支持 aarch64，当前架构为: $(uname -m)"
}

trim() {
    local value="$1"
    value="${value#"${value%%[![:space:]]*}"}"
    value="${value%"${value##*[![:space:]]}"}"
    printf '%s' "${value}"
}

read_base_url() {
    local value
    while true; do
        printf '%s' "请输入 API Base URL（例如 https://api.example.com）: " >/dev/tty
        IFS= read -r value </dev/tty || die "读取 Base URL 失败。"
        value="$(trim "${value}")"

        [[ -n "${value}" ]] || {
            info "Base URL 不能为空。" >/dev/tty
            continue
        }
        [[ "${value}" =~ ^https?://[^[:space:]/]+([/?#][^[:space:]]*)?$ ]] || {
            info "Base URL 必须包含有效主机名，以 http:// 或 https:// 开头，且不能包含空格。" >/dev/tty
            continue
        }
        while [[ "${value}" == */ ]]; do
            value="${value%/}"
        done
        [[ "${value}" != */v1/messages ]] || {
            info "请输入 API 基础地址，不要填写 /v1/messages。" >/dev/tty
            continue
        }
        printf '%s' "${value}"
        return
    done
}

read_api_key() {
    local value
    while true; do
        printf '%s' "请输入 API Key（输入内容不会显示）: " >/dev/tty
        IFS= read -r -s value </dev/tty || die "读取 API Key 失败。"
        printf '\n' >/dev/tty

        [[ -n "${value}" ]] || {
            info "API Key 不能为空。" >/dev/tty
            continue
        }
        [[ "${value}" != *[[:space:]]* ]] || {
            info "API Key 不能包含空格或换行。" >/dev/tty
            continue
        }
        printf '%s' "${value}"
        return
    done
}

confirm_overwrite() {
    [[ -f "${CONFIG_FILE}" ]] || return 0

    local answer backup_file
    printf '%s' "检测到已有配置，是否覆盖？[y/N]: " >/dev/tty
    IFS= read -r answer </dev/tty || die "读取确认失败。"
    case "${answer}" in
        y|Y|yes|YES)
            backup_file="${CONFIG_FILE}.bak.$(date +%Y%m%d%H%M%S)"
            cp -p "${CONFIG_FILE}" "${backup_file}"
            chmod 600 "${backup_file}"
            info "旧配置已备份到: ${backup_file}"
            ;;
        *)
            info "已取消，原配置未修改。"
            exit 0
            ;;
    esac
}

write_config() {
    local base_url="$1" api_key="$2" temporary_file
    mkdir -p "${CONFIG_DIR}"
    chmod 700 "${CONFIG_DIR}"
    umask 077
    temporary_file="$(mktemp "${CONFIG_DIR}/credentials.env.tmp.XXXXXX")"

    {
        printf '# Claude Code custom API configuration\n'
        printf '# Generated by configure.sh\n\n'
        printf 'ANTHROPIC_BASE_URL=%q\n' "${base_url}"
        printf 'ANTHROPIC_AUTH_TOKEN=%q\n' "${api_key}"
    } > "${temporary_file}"

    chmod 600 "${temporary_file}"
    mv -f "${temporary_file}" "${CONFIG_FILE}"
    chmod 600 "${CONFIG_FILE}"
}

main() {
    case "${1:-}" in
        -h|--help)
            usage
            return 0
            ;;
        '')
            ;;
        *)
            usage >&2
            die "未知参数: $1"
            ;;
    esac

    print_header "Claude Code 自定义 API 配置"
    info "配置文件将保存到: ${CONFIG_FILE}"
    info "API Key 只会写入本机，不会上传。"
    echo

    check_termux
    require_terminal
    confirm_overwrite

    local base_url api_key
    base_url="$(read_base_url)"
    api_key="$(read_api_key)"
    write_config "${base_url}" "${api_key}"

    echo
    success "自定义 API 配置完成。"
    printf '配置文件: %s\n' "${CONFIG_FILE}"
    printf '现在可以运行: claude\n'
}

main "$@"
